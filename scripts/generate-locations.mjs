// Builds src/data/locations.ts and src/data/stations.ts from the KPTCL location workbook.
// Usage: npm run generate:locations [-- path/to/workbook.xlsx]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import ExcelJS from 'exceljs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = process.argv[2] ?? path.join(root, 'data', 'tree_map_KPTCL.xlsx');

const clean = (v) => String(v ?? '').replace(/\s+/g, ' ').trim();
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
// Station names end in "-<code>-<voltage> KV", e.g. "ABBIGERE-1103E0923-66 KV".
const NAME = /^(.*)-([0-9A-Z]{6,12})-(\d+)\s*KV$/i;
// The letter inside a station code usually matches the class: C = 220 kV, D = 110 kV, E = 66 kV.
const CLASS_BY_LETTER = { C: '220 kV', D: '110 kV', E: '66 kV' };

const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(input);
const ws = wb.worksheets[0];
const header = ws.getRow(1).values.slice(1).map(clean);
const col = (name) => header.indexOf(name) + 1;
const C = Object.fromEntries(
  ['Zone', 'Circle', 'Division', 'Nodal', 'Station', 'Station Code', 'Voltage class', 'District', 'Taluku'].map((n) => [n, col(n)]),
);
for (const [n, i] of Object.entries(C)) if (!i) throw new Error(`Column "${n}" not found in ${input}`);

const issues = { rows: 0, badCodeCells: 0, unparsableNames: 0, repeatedRows: 0, conflicts: [], voltageFixed: [], letterMismatch: [] };
const zones = new Map();
const circles = new Map();
const divisions = new Map();
const stations = new Map();

ws.eachRow((row, n) => {
  if (n === 1) return;
  issues.rows += 1;
  const get = (k) => clean(row.getCell(C[k]).value);
  const zone = get('Zone');
  const circle = get('Circle');
  const division = get('Division');
  const m = NAME.exec(get('Station'));
  if (!zone || !circle || !division || !m) {
    issues.unparsableNames += 1;
    return;
  }
  const [, stationName, code, kv] = m;
  // Excel turned codes like 1103E0191 into numbers (1.1e+194): the real code is still in the name.
  if (get('Station Code') !== code) issues.badCodeCells += 1;

  zones.set(slug(zone), { id: slug(zone), name: zone });
  circles.set(slug(circle), { id: slug(circle), name: circle, zoneId: slug(zone) });
  divisions.set(slug(division), { id: slug(division), name: division, circleId: slug(circle) });

  const voltage = `${kv} kV`;
  const sheetVoltage = get('Voltage class').replace(/\s*KV$/i, ' kV');
  const letter = code.match(/[A-Z]/g)?.[0];
  const expected = CLASS_BY_LETTER[letter];
  if (sheetVoltage !== voltage && !issues.voltageFixed.includes(code)) issues.voltageFixed.push(code);
  if (expected && expected !== voltage && !issues.letterMismatch.includes(code)) issues.letterMismatch.push(code);

  const rec = [code, stationName.trim(), slug(division), get('Nodal'), voltage, get('District'), get('Taluku')];
  const prev = stations.get(code);
  if (!prev) stations.set(code, rec);
  else if (prev.join('|') !== rec.join('|')) issues.conflicts.push(code);
  else issues.repeatedRows += 1;
});

const byName = (a, b) => a.name.localeCompare(b.name);
const z = [...zones.values()].sort(byName);
const c = [...circles.values()].sort(byName);
const d = [...divisions.values()].sort(byName);
const s = [...stations.values()].sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));

// A circle sits under one zone and a division under one circle; fail loudly if the workbook says otherwise.
const checkUnique = (rows, key, parent, label) => {
  const seen = new Map();
  for (const r of rows) {
    const k = clean(r.getCell?.(C[key])?.value);
    if (seen.has(k) && seen.get(k) !== r.getCell(C[parent]).value) throw new Error(`${label} "${k}" appears under two parents`);
    seen.set(k, r.getCell(C[parent]).value);
  }
};
const rowsArr = [];
ws.eachRow((r, n) => n > 1 && rowsArr.push(r));
checkUnique(rowsArr, 'Circle', 'Zone', 'Circle');
checkUnique(rowsArr, 'Division', 'Circle', 'Division');

const banner = `// GENERATED by scripts/generate-locations.mjs from ${path.basename(input)}. Do not edit by hand.\n`;
const json = (v) => `[\n${v.map((x) => `  ${JSON.stringify(x)},`).join('\n')}\n]`;

writeFileSync(
  path.join(root, 'src/data/locations.ts'),
  `${banner}import type { Circle, Division, Zone } from '@/features/locations/types';

export const zones: Zone[] = ${json(z)};

export const circles: Circle[] = ${json(c)};

export const divisions: Division[] = ${json(d)};
`,
);
writeFileSync(
  path.join(root, 'src/data/stations.ts'),
  `${banner}import type { StationRecord } from '@/features/locations/types';

/** [code, name, divisionId, nodal, voltage, district, taluk] */
export const stations: StationRecord[] = ${JSON.stringify(s).replace(/\],\[/g, '],\n[')};
`,
);

console.log(`Read ${issues.rows} rows from ${path.basename(input)}`);
console.log(`Zones ${z.length}, circles ${c.length}, divisions ${d.length}, stations ${s.length}`);
console.log(`Repeated identical rows ignored: ${issues.repeatedRows}`);
console.log(`Station code cells damaged by Excel (recovered from the name): ${issues.badCodeCells}`);
console.log(`Stations whose district/taluk/voltage differ between rows (first row kept): ${issues.conflicts.length}`);
console.log(`Stations whose "Voltage class" column disagrees with the name (name used): ${issues.voltageFixed.length}`);
console.log(`Stations whose name voltage disagrees with the letter in their code (name used, worth checking): ${issues.letterMismatch.length}`);
if (issues.unparsableNames) console.log(`Rows skipped (blank level or unreadable station name): ${issues.unparsableNames}`);
